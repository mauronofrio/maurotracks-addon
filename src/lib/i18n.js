export function pickLocale(accountLocale, browserLang) {
  if (LOCALES.includes(accountLocale)) return accountLocale;
  const short = String(browserLang ?? "").slice(0, 2).toLowerCase();
  return LOCALES.includes(short) ? short : "en";
}

export function t(locale, key, params = {}) {
  const text = MESSAGES[locale]?.[key] ?? MESSAGES.it[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, name) => (name in params ? String(params[name]) : m));
}
